def esc(s):
    return s.replace('\\', '\\\\').replace('(', '\\(').replace(')', '\\)')


def draw_table(cmd, name, x, y_top, w, fields, fill, stroke):
    h = 22 + len(fields) * 16
    y_bottom = y_top - h
    cmd.append(f"{fill[0]:.3f} {fill[1]:.3f} {fill[2]:.3f} rg")
    cmd.append(f"{stroke[0]:.3f} {stroke[1]:.3f} {stroke[2]:.3f} RG 2 w")
    cmd.append(f"{x} {y_bottom} {w} {h} re B")
    cmd.append(f"{stroke[0]:.3f} {stroke[1]:.3f} {stroke[2]:.3f} rg")
    cmd.append(f"{x} {y_top - 22} {w} 22 re f")
    cmd.append(f"BT /F2 12 Tf 1 1 1 rg {x + 8} {y_top - 15} Td ({esc(name)}) Tj ET")
    for i, f in enumerate(fields):
        fy = y_top - 22 - (i + 1) * 16 + 5
        cmd.append(f"BT /F1 9 Tf 0 0 0 rg {x + 8} {fy} Td ({esc(f)}) Tj ET")
        if i < len(fields) - 1:
            ly = y_top - 22 - (i + 1) * 16
            cmd.append(f"0.85 0.85 0.85 RG 0.5 w {x} {ly} m {x + w} {ly} l S")


def draw_link(cmd, x1, y1, x2, y2, l1, l2):
    cmd.append("0.30 0.30 0.30 RG 1.5 w")
    cmd.append(f"{x1} {y1} m {x2} {y2} l S")
    cmd.append(f"0.30 0.30 0.30 rg {x1 - 3} {y1 - 3} 6 6 re f")
    cmd.append(f"0.30 0.30 0.30 rg {x2 - 3} {y2 - 3} 6 6 re f")
    mx1 = x1 + (x2 - x1) * 0.20
    my1 = y1 + (y2 - y1) * 0.20
    mx2 = x1 + (x2 - x1) * 0.80
    my2 = y1 + (y2 - y1) * 0.80
    cmd.append(f"BT /F2 11 Tf 0.80 0.00 0.00 rg {mx1:.1f} {my1 + 5:.1f} Td ({esc(l1)}) Tj ET")
    cmd.append(f"BT /F2 11 Tf 0.80 0.00 0.00 rg {mx2:.1f} {my2 + 5:.1f} Td ({esc(l2)}) Tj ET")


